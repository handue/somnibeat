"""Render README.md and docs/WRITEUP.md from templates, filling every number from results JSON.

No result number is typed by hand in the documents: the templates in
docs/templates/ contain placeholders that point into the results files.

Placeholder syntax (inside {{ }}):
    p:<path>:<decimals>     point estimate of a bootstrap metric   -> "50.9"
    ci:<path>:<decimals>    its 95% interval                       -> "35.2 to 68.9"
    pm:<path>:<decimals>    point with interval                    -> "50.9 (95% CI 35.2 to 68.9)"
    v:<path>[:<decimals>]   any value (integers print as-is)
    pct:<path>:<decimals>   a fraction shown as a percentage       -> "99.9"
    sgn:<path>:<decimals>   point with an explicit sign            -> "+12.3"
    len:<path>              number of items in a list or dict      -> "36"
    keys:<path>             the keys of a dict, comma-separated    -> "SN001, SN036"

<path> is "<file>/<key>/<key>/...", where <file> is a results JSON name
without extension (sleep_wake, wake_nrem_rem, four_class, apnea,
rpeak_validation, data_check) or "v2_<stem>" for results/v2/<stem>.json
(v2_test_results, v2_v2_selection, v2_v2_final_spec, v2_hmc_check, ...).
Metric paths may stop at the metric name.

Usage:
    python scripts/render_docs.py            # write README.md and docs/WRITEUP.md
    python scripts/render_docs.py --check    # exit 1 if they are out of date
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEMPLATES = {ROOT / "docs/templates/README.md.tmpl": ROOT / "README.md",
             ROOT / "docs/templates/WRITEUP.md.tmpl": ROOT / "docs/WRITEUP.md"}
# Local-only drafts (git-ignored private/ folder): rendered when present, without the header comment.
PRIVATE_TEMPLATES = {ROOT / "private/DEVPOST.md.tmpl": ROOT / "private/DEVPOST.md"}
PLACEHOLDER = re.compile(r"\{\{\s*([a-z]+):([^:}\s]+)(?::(\d+))?\s*\}\}")
HEADER = "<!-- Generated by scripts/render_docs.py from {tmpl}. Edit the template, not this file. -->\n"


def load_results() -> dict:
    out = {}
    for f in sorted((ROOT / "results").glob("*.json")):
        out[f.stem] = json.loads(f.read_text())
    for f in sorted((ROOT / "results/v2").glob("*.json")):
        out[f"v2_{f.stem}"] = json.loads(f.read_text())
    return out


def lookup(results: dict, path: str):
    parts = path.split("/")
    node = results[parts[0]]
    for p in parts[1:]:
        node = node[int(p)] if isinstance(node, list) else node[p]
    return node


def fmt(x: float, dec: int) -> str:
    s = f"{x:.{dec}f}"
    return f"{0.0:.{dec}f}" if float(s) == 0 else s  # never print "-0.0"


def render_one(kind: str, path: str, dec: str | None, results: dict) -> str:
    node = lookup(results, path)
    d = int(dec) if dec is not None else 1
    if kind == "p":
        return fmt(node["point"], d)
    if kind == "ci":
        return f"{fmt(node['ci_low'], d)} to {fmt(node['ci_high'], d)}"
    if kind == "pm":
        return f"{fmt(node['point'], d)} (95% CI {fmt(node['ci_low'], d)} to {fmt(node['ci_high'], d)})"
    if kind == "sgn":
        v = node["point"] if isinstance(node, dict) else node
        s = fmt(v, d)
        return s if s.startswith("-") or float(s) == 0 else "+" + s
    if kind == "pct":
        v = node["point"] if isinstance(node, dict) else node
        return fmt(100.0 * v, d)
    if kind == "len":
        return str(len(node))
    if kind == "keys":
        return ", ".join(str(k) for k in node)
    if kind == "v":
        if isinstance(node, bool) or isinstance(node, str):
            return str(node)
        if isinstance(node, int) and dec is None:
            return str(node)
        return fmt(float(node), d)
    raise ValueError(f"unknown placeholder kind {kind!r}")


def render(text: str, results: dict) -> str:
    def sub(m):
        return render_one(m.group(1), m.group(2), m.group(3), results)
    return PLACEHOLDER.sub(sub, text)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    results = load_results()
    stale = []
    jobs = [(t, o, True) for t, o in TEMPLATES.items()]
    jobs += [(t, o, False) for t, o in PRIVATE_TEMPLATES.items() if t.exists()]
    for tmpl, out, public in jobs:
        body = render(tmpl.read_text(), results)
        if "{{" in body:
            raise SystemExit(f"{tmpl}: unrendered placeholder near {body[body.index('{{'):][:60]!r}")
        text = (HEADER.format(tmpl=tmpl.relative_to(ROOT)) if public else "") + body
        if a.check:
            if not out.exists() or out.read_text() != text:
                stale.append(str(out.relative_to(ROOT)))
        else:
            out.write_text(text)
            print(f"wrote {out.relative_to(ROOT)}")
    if stale:
        print("Out of date (run `make docs`):", *stale)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
