"""Apply the candidate-1 rule (docs/v2_protocol.md) and write the frozen v2 specification.

Candidate 1 (all usable CAP records) is judged on cross-dataset fold A only
(train CAP -> evaluate MIT-BIH slpdb), against the same spec trained on the v1
CAP subset: accepted if fold-A sleep/wake kappa improves by at least the tie
margin (0.01) and fold-A total-sleep-time MAE is not more than 10 % worse.
It is checked twice: for the v1 reference spec alone, and combined with the
staging candidate chosen in results/v2/v2_selection.json.

Inputs (training data only):
  results/v2/selection_staging.json   49 CAP records (v1 subset)
  results/v2/selection_cap106.json    106 CAP records
  results/v2/v2_selection.json        chosen staging and apnea specs
Outputs:
  results/v2/v2_final_spec.json
  docs/v2_final_spec.md
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TIE = 0.01
GUARD = 1.10


def fold_a(path: Path, name: str) -> dict:
    r = json.loads(path.read_text())
    cands = r["candidates"] if "candidates" in r else r
    for c in (cands if isinstance(cands, list) else cands.values()):
        cname = c.get("name") or c.get("spec", {}).get("name")
        if cname == name and c.get("tasks", {}).get("sleep_wake"):
            m = c["tasks"]["sleep_wake"]["cross_dataset"]["train_cap_eval_slpdb"]["sleep_wake"]
            return {"kappa": m["kappa_pooled"]["point"], "tst_mae_min": m["tst_mae_min"]["point"],
                    "kappa_ci": [m["kappa_pooled"]["ci_low"], m["kappa_pooled"]["ci_high"]]}
    raise KeyError(f"{name} not in {path}")


def judge(base: dict, cand: dict) -> dict:
    dk = cand["kappa"] - base["kappa"]
    ok_guard = cand["tst_mae_min"] <= GUARD * base["tst_mae_min"]
    return {"kappa_gain": dk, "guard_ok": ok_guard, "accepted": bool(dk >= TIE and ok_guard)}


def main() -> int:
    sel = json.loads((ROOT / "results/v2/v2_selection.json").read_text())
    chosen = sel["staging"]["chosen"]["name"]
    s49, s106 = ROOT / "results/v2/selection_staging.json", ROOT / "results/v2/selection_cap106.json"
    rows = {}
    for spec in ("v1_reference", chosen):
        rows[spec] = {"cap49": fold_a(s49, spec), "cap106": fold_a(s106, spec)}
        rows[spec]["decision"] = judge(rows[spec]["cap49"], rows[spec]["cap106"])
    use106 = rows[chosen]["decision"]["accepted"]
    st = sel["staging"]["chosen"]
    final = {
        "protocol": "docs/v2_protocol.md (candidate-1 clarification)",
        "rule": {"fold": "train CAP -> evaluate slpdb (fold A)", "tie_margin": TIE, "tst_guard": GUARD},
        "candidate_1": rows,
        "staging": {"model": st["model"], "class_weight": st["class_weight"], "smoothing": st["smoothing"],
                    "feature_set": st["feature_set"],
                    "cap_records": "all usable (config/v2.toml)" if use106 else "v1 subset (config/default.toml)"},
        "apnea": {k: sel["apnea"]["chosen"][k] for k in sel["apnea"]["chosen"]
                  if k in ("model", "class_weight", "feature_set", "train", "name")},
        "hyperparameters": sel["hyperparameters"],
    }
    (ROOT / "results/v2/v2_final_spec.json").write_text(json.dumps(final, indent=2))

    def f(x):
        return f"{x:.3f}"
    lines = ["# v2 final specification", "",
             "Generated by `scripts/v2_decide_final.py` from training-data results only.", "",
             "## Candidate 1: all usable CAP records (fold A: train CAP -> evaluate slpdb)", "",
             "| Spec | Kappa, 49 CAP | Kappa, 106 CAP | Gain | TST MAE 49 / 106 (min) | Accepted |",
             "|---|---|---|---|---|---|"]
    for spec, r in rows.items():
        d = r["decision"]
        lines.append(f"| `{spec}` | {f(r['cap49']['kappa'])} | {f(r['cap106']['kappa'])} | {d['kappa_gain']:+.3f} | "
                     f"{r['cap49']['tst_mae_min']:.1f} / {r['cap106']['tst_mae_min']:.1f} | "
                     f"{'yes' if d['accepted'] else 'no'} |")
    lines += ["", "## Frozen v2", "",
              f"- Staging: `{chosen}`, trained on {final['staging']['cap_records']} CAP records + MIT-BIH slpdb.",
              f"- Apnea: `{final['apnea'].get('name', final['apnea'])}`.",
              "- HMM transitions and the initial distribution come from the training labels; the model is",
              "  applied to every epoch of a night and smoothed over the whole night, exactly as the demo does.",
              ""]
    (ROOT / "docs/v2_final_spec.md").write_text("\n".join(lines))
    print(json.dumps({k: v["decision"] for k, v in rows.items()}, indent=1))
    print("use 106 CAP:", use106)
    return 0


if __name__ == "__main__":
    sys.exit(main())
